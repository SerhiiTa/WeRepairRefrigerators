\set ON_ERROR_STOP on
begin;
create function pg_temp.check_ok(ok boolean,label text) returns void language plpgsql as $$begin if ok is distinct from true then raise exception 'FAIL %',label;end if;raise notice 'PASS %',label;end$$;
do $$
declare co uuid:='00000000-0000-4000-8000-000000000010';u uuid:='00000000-0000-4000-8000-000000000001';c uuid:='00000000-0000-4000-8000-000000000020'; n uuid; d staff_notification_deliveries; token uuid; count_before bigint;
begin
 insert into companies values(co),('00000000-0000-4000-8000-000000000011');
 insert into profiles(id) values(u),('00000000-0000-4000-8000-000000000002');
 insert into company_members(company_id,profile_id,member_role) values(co,u,'owner');
 insert into communication_conversations(id,company_id) values(c,co);
 insert into communication_messages values(gen_random_uuid(),c,'sms','inbound','customer');
 perform pg_temp.check_ok(not exists(select 1 from staff_notification_deliveries),'no preference = no external queue');
 insert into staff_notification_preferences(company_id,recipient_profile_id,event_type,push_enabled) values(co,u,'inbound_sms',true);
 insert into communication_messages values(gen_random_uuid(),c,'sms','inbound','customer');
 perform pg_temp.check_ok((select count(*)=1 and bool_and(channel='push') from staff_notification_deliveries),'event-specific opt-in only');
 select notification_id into n from staff_notification_deliveries;
 begin insert into staff_notification_deliveries(notification_id,channel,dedupe_key) values(n,'push','duplicate');raise exception 'duplicate allowed';exception when unique_violation then raise notice 'PASS stable notification/channel dedupe';end;
 update staff_notification_preferences set quiet_start='00:00',quiet_end='00:00';
 perform pg_temp.check_ok(not exists(select 1 from claim_staff_notification_deliveries(array['push'],5)),'quiet hours defer');
 update staff_notification_preferences set high_priority_bypass=true;
 perform pg_temp.check_ok(staff_delivery_policy(n,'push')='quiet_hours','normal priority never bypasses');
 update staff_notifications set priority='high' where id=n;
 perform pg_temp.check_ok(staff_delivery_policy(n,'push')='allowed','explicit high priority exception');
 update staff_notification_preferences set push_enabled=false;
 perform pg_temp.check_ok(staff_delivery_policy(n,'push')='opted_out','priority cannot override opt-out');
 update staff_notification_preferences set push_enabled=true,quiet_start=null,quiet_end=null;
 select * into d from claim_staff_notification_deliveries(array['push'],1);
 perform pg_temp.check_ok(d.attempt_count=1 and d.lease_token is not null,'atomic claim and attempt');
 perform pg_temp.check_ok(not exists(select 1 from claim_staff_notification_deliveries(array['push'],1)),'active lease not reclaimed');
 perform pg_temp.check_ok(authorize_staff_notification_delivery(d.id,d.lease_token)->>'recipientProfileId'=u::text,'staff-only dispatch context');
 perform pg_temp.check_ok(not finish_staff_notification_delivery(d.id,gen_random_uuid(),'sent'),'wrong lease cannot finish');
 perform pg_temp.check_ok(finish_staff_notification_delivery(d.id,d.lease_token,'retryable',null,'429','rate_limited',120),'explicit rejection retry stored');
 perform pg_temp.check_ok((select status='failed' and next_attempt_at>clock_timestamp()+interval '110 seconds' from staff_notification_deliveries where id=d.id),'retry-after honored');
 update staff_notification_deliveries set next_attempt_at=clock_timestamp()-interval '1 second';
 select * into d from claim_staff_notification_deliveries(array['push'],1);
 perform finish_staff_notification_delivery(d.id,d.lease_token,'accepted','receipt-1','accepted');
 perform pg_temp.check_ok((select status='processing' and lease_until is null from staff_notification_deliveries where id=d.id),'accepted awaiting receipt, no resend');
 insert into communication_messages values(gen_random_uuid(),c,'sms','inbound','customer');
 select * into d from claim_staff_notification_deliveries(array['push'],1);
 update staff_notification_deliveries set lease_until=clock_timestamp()-interval '1 second' where id=d.id;
 perform claim_staff_notification_deliveries(array['push'],1);
 perform pg_temp.check_ok((select status='permanently_failed' and error_code='delivery_outcome_unknown' from staff_notification_deliveries where id=d.id),'expired lease quarantined, not resent');
 insert into communication_messages values(gen_random_uuid(),c,'sms','inbound','customer');
 select * into d from claim_staff_notification_deliveries(array['push'],1);
 update company_members set member_status='suspended' where profile_id=u;
 perform pg_temp.check_ok(authorize_staff_notification_delivery(d.id,d.lease_token) is null,'membership revoked after claim blocks dispatch');
 update company_members set member_status='active';
 insert into communication_messages values(gen_random_uuid(),c,'sms','inbound','customer');
 update staff_notification_deliveries set attempt_count=5 where status='queued';
 perform claim_staff_notification_deliveries(array['push'],1);
 perform pg_temp.check_ok(not exists(select 1 from staff_notification_deliveries where attempt_count=5 and status<>'permanently_failed'),'retry ceiling');
 perform set_config('request.jwt.claim.sub',u::text,true);
 execute 'set local role authenticated';
 perform pg_temp.check_ok((select count(*)=4 from staff_notification_deliveries),'own delivery history visible');
 begin perform claim_staff_notification_deliveries(array['sms'],1);raise exception 'browser claim allowed';exception when insufficient_privilege then raise notice 'PASS browser cannot claim';end;
 execute 'reset role';
 perform set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000002',true);
 execute 'set local role authenticated';
 perform pg_temp.check_ok(not exists(select 1 from staff_notification_deliveries),'foreign staff cannot read history');
 execute 'reset role';
 perform pg_temp.check_ok(not exists(select 1 from communication_messages where direction='outbound'),'no customer SMS generated');
end$$;
rollback;
